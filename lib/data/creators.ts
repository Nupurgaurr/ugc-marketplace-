/** Only approved creators are ever exposed to the public/client side. */
export function getApprovedCreators(): Creator[] {
  return creators.filter((c) => c.status === 'approved');
}

export function getCreatorBySlug(slug: string): Creator | undefined {
  return creators.find((c) => c.slug === slug);
}

export function getCreatorById(id: string): Creator | undefined {
  return creators.find((c) => c.id === id);
}

export function getPendingCreators(): Creator[] {
  return creators.filter((c) => c.status === 'applied' || c.status === 'in_review');
}

export function setCreatorStatus(id: string, status: Creator['status']): void {
  const creator = creators.find((c) => c.id === id);
  if (!creator) return;
  creator.status = status;
  if (status === 'approved') creator.approvedAt = new Date().toISOString().slice(0, 10);
}

